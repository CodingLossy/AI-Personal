export const dictionaries: Record<Locale, Record<Key, string>> = { 'zh-CN': zh, en };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
    const dict = dictionaries[locale];
    return (key, vars) => dict[key].replace(/\{(\w+)\}/g, (m, name: string) => String(vars?.[name] ?? m));
}

export const I18nContext = createContext<{ locale: Locale; t: Translate }>({
    locale: 'zh-CN',
    t: translator('zh-CN'),
});

export const useI18n = () => useContext(I18nContext);
